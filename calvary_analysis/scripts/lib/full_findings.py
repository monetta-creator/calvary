"""Regenerate reports/full_findings.md from its sources, so it cannot drift from them (review finding R11).

Inputs: modules/m*.md (the readouts, in module order), insight_register.csv, recommendations/funding_pressure_verdict.md
and discoveries_log.md. The report adds no numbers of its own: edit a readout or rerun a module, then rerun this.
Run after the modules (README rerun order): calvary_funding_data/.venv/bin/python calvary_analysis/scripts/lib/full_findings.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from lib.common import ANALYSIS, AS_OF, REGISTER  # noqa: E402

OUT = ANALYSIS / "reports" / "full_findings.md"
MODULES = ["m1_calvary_trajectory", "m2_government_exposure", "m3_peer_benchmarking", "m4_funder_landscape", "m5_funder_gaps",
           "m6_network", "m7_pipeline", "m8_expansion_scan", "m9_need_capacity", "m10_comparator_profiles"]


def readout(name: str) -> tuple[str, str]:
    """(title, body) of one module readout, headings pushed down one level so they nest under the report."""
    text = (ANALYSIS / "modules" / f"{name}.md").read_text().strip()
    first, _, body = text.partition("\n")
    title = re.sub(r"^#\s*", "", first).replace(" readout:", "")
    body = re.sub(r"(?m)^(#{2,5}) ", lambda m: "#" + m.group(1) + " ", body.strip())
    return title, body


def section(md: str, heading: str) -> str:
    """The text under '## heading' up to the next '## ' heading."""
    m = re.search(rf"(?ms)^## {re.escape(heading)}\s*\n(.*?)(?=^## |\Z)", md)
    return m.group(1).strip() if m else ""


def main() -> int:
    reg = pd.read_csv(REGISTER, dtype=str).fillna("")
    reg["mod_n"] = reg.module.str[1:].astype(int)
    reg["n"] = reg.insight_id.str.split("-").str[1].astype(int)
    reg = reg.sort_values(["mod_n", "n"])
    statuses = sorted(set(reg.status))
    verdict = (ANALYSIS / "recommendations" / "funding_pressure_verdict.md").read_text()
    flags = [l for l in (ANALYSIS / "discoveries_log.md").read_text().splitlines() if re.match(r"^\| D\d", l)]

    out = ["# Calvary Women's Services: Full Findings Report (All Modules)", "",
           "**Audience:** consulting team  ",
           f"**As of:** data {AS_OF}; text regenerated by `scripts/lib/full_findings.py` from the module readouts, the insight register, "
           "the verdict and the discoveries log (revised after the October 2026 independent review, `reports/review/`)  ",
           "**Covers:** modules M1–M10, the funding-pressure verdict, discovery flags D1–D3 and the insight register", "",
           "**Purpose.** One document with every module's question, method, findings, charts, caveats and confidence, around the two "
           "anchor questions: how much funding pressure Calvary's reliance on government creates, and which other funding fits. "
           "Every chart ID maps to `chart_data/<id>.csv`; `scripts/lib/trace.py` checks the chain to the source registry.", "",
           "---", "", "## Summary of findings", "",
           "One line per register finding, in module order. The module sections below carry the evidence.", ""]
    for mod, g in reg.groupby("mod_n", sort=True):
        title = readout(MODULES[mod - 1])[0]
        out.append(f"**{title}.** " + " ".join(r.finding.strip() for r in g.itertuples()))
        out.append("")
    out += ["---", ""]
    for name in MODULES:
        title, body = readout(name)
        out += [f"## {title}", "", body, "", "---", ""]

    out += ["## The verdict", "", "From `recommendations/funding_pressure_verdict.md`; the full evidence table is there.", ""]
    out += [section(verdict, "Verdict in one paragraph"), ""]
    change = section(verdict, "What would change the verdict")
    if change:
        out += ["**What would change the verdict**", "", change, ""]
    out += ["---", "", "## Discovery flags", "", "From `discoveries_log.md` (full evidence and responses there).", "",
            "| # | date | finding | evidence | why it matters | proposed action | response |", "|---|---|---|---|---|---|---|", *flags, "",
            "---", "", "## Insight register summary", "",
            f"All {len(reg)} rows of `insight_register.csv` in module order (status: {', '.join(statuses)}).", "",
            "| insight_id | finding | magnitude | confidence | status |", "|---|---|---|---|---|"]
    out += [f"| {r.insight_id} | {r.finding.replace('|', '/')} | {r.magnitude.replace('|', '/')} | {r.confidence} | {r.status} |" for r in reg.itertuples()]
    out += ["", "---", "", "## Source note", "",
            "Every chart ID in this report maps to `chart_data/<id>.csv`, listed in `chart_data/_manifest.csv` with its title, source "
            "tables, source IDs, script and row count. Each CSV's `source_ids` map to `calvary_funding_data/sources/source_registry.csv` "
            "or `sources/source_registry_extension.csv`. Funder open status comes from `config/guideline_notes.csv` (funders' own pages, "
            "October 2026).", ""]
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT.relative_to(ANALYSIS.parent)}: {len(reg)} register rows, {len(MODULES)} modules, {len(flags)} flags")
    return 0


if __name__ == "__main__":
    sys.exit(main())
